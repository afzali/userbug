/**
 * دیتابیس تستِ سرور لوکال نپی را از نو شروع کن.
 *
 * از قلاب `beforeRun` در `targets/nepi.config.js` صدا زده می‌شود. جدا نوشته شد
 * چون همین چند خط به‌شکل `node -e "…"` درون‌خطی، با نقل‌قول‌های تودرتوی شل و
 * جاوااسکریپت درگیر می‌شد — و قلابی که بی‌صدا خراب باشد، اجرا را روی وضعیت
 * اشتباه می‌برد.
 */
import fs from 'node:fs';

const BASE = 'D:/Projects/nepi/nepi-data/nepi-test.sqlite';

let removed = 0;
// فایل‌های جانبیِ WAL هم باید بروند، وگرنه دیتابیسِ «پاک‌شده» با تراکنش‌های
// قبلی دوباره سر جایش می‌آید.
for (const suffix of ['', '-wal', '-shm']) {
  try {
    fs.rmSync(BASE + suffix);
    removed++;
  } catch {
    // نبودنش عادی است: اولین اجرا، یا اجرای قبلی که تمیز بسته شده
  }
}

console.log(`دیتابیس تست: ${removed} فایل پاک شد`);
