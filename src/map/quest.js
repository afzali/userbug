/**
 * «برو این یکی را بررسی کن» — نقشه راه را می‌برد، کاوش فکر می‌کند.
 *
 * ── چرا این سومی لازم بود، در حالی که دو تا داشتیم ──
 *
 * نقشه کامل است ولی **بی‌هدف**: همه‌جا می‌رود و هیچ‌جا عمیق نمی‌شود. کاوش
 * هدف دارد ولی **کور** شروع می‌کند: از صفحهٔ اول، و هر قدمِ ناوبری یک
 * فراخوانی مدل است تا برسد جایی که اصلاً قرار بود کارش را شروع کند.
 *
 * ترکیبشان هر دو نقص را می‌برد:
 *
 *   رسیدن به آن نما   →  مسیرِ نقشه (`path`)     صفر فراخوانی
 *   گشتنِ هدف‌دار      →  explore با هدفِ شما     چند فراخوانی، سقف‌دار
 *   خروجی             →  پیش‌نویسِ سناریو        با مقدمهٔ قطعی
 *
 * ── چرا ماشینِ تازه‌ای ساخته نمی‌شود ──
 *
 * `explore` از اول `preamble` می‌گیرد و `run.js` هم `ctx.executed` را به آن
 * می‌دهد. یعنی اگر قدم‌های ناوبری **پیش از** فعلِ `explore` در سناریو
 * بنشینند، پیش‌نویسِ خروجی خودش همان‌ها را به‌عنوان مقدمه می‌گیرد.
 *
 * پس quest فقط یک سناریوی کوچک می‌نویسد و از همان اجراگرِ همیشگی ردش
 * می‌کند. نه مسیرِ اجرای دوم، نه داورِ دوم، نه گزارشِ دوم.
 */
import { focusWords } from './state.js';

/**
 * واژه‌هایی که در امتیازدهی نباید شمرده شوند.
 *
 * ── چرا این فهرست لازم شد ──
 *
 * روی نقشهٔ واقعیِ نپی، هدفِ «خروج از حساب» به نمای «تنظیمات هوش مصنوعی»
 * رسید — چون «از» در «تنظیمات هوش مصنوعی» نبود، در `از` بود که خودش داخلِ
 * واژهٔ دیگری نشسته بود. حرفِ اضافه در هر جمله‌ای هست، پس هر هدفی را به یک
 * نمای تصادفی وصل می‌کند، و کاربر آن را «نقشه بلد بود» می‌خواند.
 *
 * `focusWords` این‌ها را نگه می‌دارد و درست هم هست: آنجا اولویت است و
 * اشتباهش فقط ترتیب را عوض می‌کند. اینجا اشتباهش مقصد را عوض می‌کند.
 */
const STOPWORDS = new Set([
  'از','به','با','در','که','را','این','آن','هم','یا','تا','بر','چه','چی','کن','کند','می','برای','روی','کدام','چطور','چگونه','وقتی','اگر','است','هست','شود','شد','باید','بررسی','چک','تست','آزمون','ببین','بزن','برو',
  'the','a','an','of','to','in','on','is','it','and','or','for','what','when','check','test','see','go',
]);

/**
 * کدام حالتِ نقشه به این هدف نزدیک‌تر است؟
 *
 * امتیاز از سه جا می‌آید و هر سه از نقشه‌اند، نه از مدل: نامِ نما، الگوی
 * روت، و برچسبِ کنش‌های همان حالت.
 *
 * `null` یعنی «هیچ‌کدام» — و آن‌وقت کاوش از صفحهٔ اول شروع می‌کند. این
 * صادقانه‌تر از بردنِ کاربر به نزدیک‌ترین حالتِ بی‌ربط است.
 */
export function pickState(map, goal) {
  const words = focusWords(goal).filter((word) => !STOPWORDS.has(word));
  if (!words.length) return null;

  const norm = (text) => String(text ?? '').replace(/‌/g, '').toLowerCase();
  let best = null;

  for (const state of map?.states || []) {
    const view = norm(state.view);
    const route = norm(state.route);
    const labels = norm((state.actions || []).map((action) => action.label).join(' '));

    let score = 0;
    const hits = [];
    for (const word of words) {
      // نامِ نما از همه گویاتر است: «افزودن کتاب جدید» خودِ همان کار است
      if (view.includes(word)) (score += 5), hits.push(word);
      else if (route.includes(word)) (score += 3), hits.push(word);
      else if (labels.includes(word)) (score += 1), hits.push(word);
    }
    if (!score) continue;

    // مسیرِ کوتاه‌تر برنده است: مقدمهٔ کوتاه‌تر کمتر می‌شکند
    const depth = state.path?.length || 0;
    if (!best || score > best.score || (score === best.score && depth < best.depth)) {
      best = { state, score, depth, hits: [...new Set(hits)] };
    }
  }

  return best;
}

/**
 * سناریوی رانندهٔ quest.
 *
 * `status: draft` است و باید بماند: این فایل خروجی نیست، **موتور** است. آنچه
 * آدم بعداً بازبینی می‌کند، پیش‌نویسی است که `writeDraft` از دلِ همین اجرا
 * می‌نویسد.
 *
 * ترتیب عمدی است — ورود، بعد مسیرِ نقشه، بعد کاوش — چون `ctx.executed` هرچه
 * پیش از `explore` اجرا شده را به‌عنوان مقدمه به پیش‌نویس می‌دهد.
 */
export function questScenario({ goal, entrySteps = [], path = [], depth }) {
  /**
   * بی ورود هم مبدأ لازم است.
   *
   * `{ go: '/' }` همان پیش‌فرضِ `session.js` است (`entryPath`)، و باید همان
   * بماند: مسیرهای نقشه نسبت به این نقطه ضبط شده‌اند.
   */
  /**
   * بی ورود، مبدأ + بستنِ مزاحم.
   *
   * ── چرا فقط وقتی سناریوی ورود نیست ──
   *
   * پنجره‌ای که با بارگذاری می‌آید، نخستین کلیک را می‌خورد؛ خزش این را در
   * کدِ خودش حل کرده و مسیرهای نقشه بی آن بازپخش نمی‌شوند. ولی وقتی کاربر
   * سناریوی ورود داده، آن سناریو صاحبِ این تصمیم است — تزریقِ قدم به فایلِ
   * کسِ دیگر یعنی پیش‌نویسِ خروجی قدمی دارد که در هیچ فایلی نوشته نشده.
   *
   * و این قدم است نه رفتارِ پنهان: در YAML دیده می‌شود، و هر پنجره‌ای که
   * ببندد **یافته** ثبت می‌کند — پنجره‌ای که جلوی کاربر می‌آید نقص است،
   * حتی وقتی بسته شد.
   */
  const entry = entrySteps.length ? entrySteps : [{ go: '/' }, { dismissBlockers: { wait: 5000 } }];
  const steps = [...entry, ...path];
  steps.push(depth ? { explore: { goal, maxSteps: depth, author: true } } : { explore: { goal, author: true } });

  /**
   * مهلت، وگرنه کاوش وسطِ کار بریده می‌شود.
   *
   * نخستین اجرای واقعی با مهلتِ پیش‌فرضِ ۱۲۰ ثانیه تمام شد و **صفر قدم**
   * ثبت کرد: قدم‌های قطعی وقت بردند و کاوش تازه شروع شده بود. اجرایی که
   * چیزی ننویسد از اجرای نشده بدتر است — هزینه‌اش را داده‌ای و خروجی ندارد.
   *
   * سقفِ کاوش (`maxSteps`) پیش‌فرضِ `explore` ۱۲ است، و هر قدمش یک فراخوانی
   * مدل و یک کنش در مرورگر: ۴۵ ثانیه برای هر کدام دست‌ودل‌بازانه ولی امن.
   */
  const steps_ = depth || 12;

  return {
    name: `کاوشِ هدف‌دار: ${String(goal).slice(0, 80)}`,
    status: 'draft',
    persona: 'pro',
    timeout: 120_000 + steps_ * 45_000,
    steps,
  };
}

/** نامِ فایل، از هدف. فارسی می‌ماند چون فهرستِ فایل‌ها را آدم می‌خواند. */
export function questSlug(goal) {
  const base = String(goal)
    .trim()
    .replace(/[^\p{L}\p{N}]+/gu, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48);
  return `کاوش-${base || 'بی‌نام'}`;
}
