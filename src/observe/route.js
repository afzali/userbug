/**
 * «کاربر کجا بود؟» — یک تعریف، نه سه تا.
 *
 * ── چرا این فایل هست ──
 *
 * سه جا همین کار را می‌کردند و هر سه یک شکل: `new URL(page.url()).pathname`.
 * ساده به نظر می‌رسد و یک تلهٔ خاموش دارد: مرورگر پیش از نخستین ناوبری روی
 * `about:blank` است، و `new URL('about:blank').pathname` می‌دهد `'blank'`.
 *
 * نتیجه‌اش تا امروز فقط یک برچسبِ عجیب در گزارش بود. با آمدنِ حلقهٔ یادگیری
 * تبدیل شد به یک **روتِ ساختگی در شناخت** به‌علاوهٔ یک پرسشِ بی‌جواب که آدم
 * باید وقت بگذارد و جوابش بدهد. شناختی که خودش را با زباله پر کند، به‌مرور
 * بدتر می‌شود نه بهتر.
 *
 * پس یک تابع، با یک قاعده: آدرسی که صفحهٔ اپ نیست، مسیر هم ندارد.
 */

/** طرح‌هایی که صفحهٔ اپ نیستند. `file:` می‌ماند چون خودآزماها با آن کار می‌کنند. */
const NOT_A_PAGE = /^(about|chrome|chrome-error|devtools|data|blob|javascript|view-source):/i;

/**
 * مسیرِ نسبیِ یک آدرس، یا `null` اگر صفحهٔ اپ نباشد.
 *
 * `null` برمی‌گرداند نه رشتهٔ خالی: مصرف‌کننده‌ها با `null` می‌فهمند «مسیری
 * نبود» و با `''` ممکن است آن را ریشه بخوانند.
 */
export function routeOf(url) {
  const raw = String(url ?? '').trim();
  if (!raw || NOT_A_PAGE.test(raw)) return null;
  try {
    return new URL(raw).pathname;
  } catch {
    return null;
  }
}
