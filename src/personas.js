/**
 * پرسوناها.
 *
 * ── چرا این‌ها فقط «تأخیر» نیستند ──
 *
 * وسوسه‌انگیز است که پرسونا را تزئین بدانیم: چه فرقی می‌کند تست سریع بزند یا
 * آهسته؟ ولی یافتهٔ ۵ نپی دقیقاً از همین‌جا آمد — بررسی یکتاییِ عنوان ۵۰۰
 * میلی‌ثانیه تأخیر دارد، پس کاربرِ تند از کنارش رد می‌شود و کاربرِ آهسته
 * نمی‌شود. همان سناریو با دو پرسونا، دو رفتار متفاوتِ اپ را می‌بیند.
 *
 * پس تأخیرها اینجا عدد دلخواه نیستند؛ هرکدام نسبت به آستانه‌های واقعیِ اپ
 * انتخاب شده‌اند: زیر ۵۰۰ برای `pro` و بالای آن برای `novice`.
 *
 * `chaos` عمداً اینجا نیست: مُدی است که روی هر پرسونا سوار می‌شود، نه پرسونای
 * سوم. فعل‌هایش در سناریو صریح نوشته می‌شوند تا قطعی بمانند.
 */

export const PERSONAS = {
  /** آهسته، متن‌ها را می‌خواند، بین کنش‌ها مکث می‌کند. */
  novice: {
    /** پیش از هر کلیک */
    actionDelay: 350,
    /** فاصلهٔ بین حروف هنگام تایپ — از آستانهٔ ۵۰۰ عبور می‌کند */
    typeDelay: 60,
    /** پس از ناوبری، پیش از کنش بعدی */
    settle: 500,
  },

  /** سریع، کیبورد، میان‌بر. مقدارها عمداً صفرند تا مسابقه‌ها را ببرد. */
  pro: {
    actionDelay: 0,
    typeDelay: 0,
    settle: 0,
  },
};

export function resolvePersona(name) {
  const persona = PERSONAS[name];
  if (!persona) {
    throw new Error(`پرسونای ناشناخته: «${name}». موجود: ${Object.keys(PERSONAS).join('، ')}`);
  }
  return { name, ...persona };
}
