/**
 * بَنچ — یک اسم روی چند اجرا، تا بعداً بشود پرسید «کدام بار؟».
 *
 * ── چرا لازم شد ──
 *
 * تا امروز هر یافته می‌گفت در کدام **اجرا** دیده شده، و اجرا یک رشتهٔ تاریخ
 * بود. وقتی کسی سه سناریو را پیش از انتشار می‌برد و فردا همان سه را بعد از
 * یک تغییر، در تریاژ دو ستونِ هم‌شکل می‌دید و هیچ‌کدام نمی‌گفت کدام کدام
 * است. اسم همان چیزی است که آدم در ذهنش دارد و ماشین نداشت.
 *
 * ── چرا ماژولِ جدا، برای این‌قدر کم ──
 *
 * سه مصرف‌کننده دارد که هر سه می‌توانستند نسخهٔ خودشان را بنویسند: خط
 * فرمان، کارگزارِ رابط، و آزمون. `--grep`ِ ساخته‌شده از نامِ فارسی اگر یک
 * جا escape شود و جای دیگر نه، نتیجه‌اش «صفر تست اجرا شد» بی هیچ خطاست —
 * همان شکستِ خاموشی که این مخزن یک بار با `shell: true` خورد.
 */

/** نامِ بنچ: کوتاه، تمیز، و اختیاری. خالی یعنی «بی‌نام»، نه خطا. */
export function normalizeBench(name) {
  return String(name ?? '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 60);
}

/**
 * چند سناویِ انتخاب‌شده → یک `--grep`.
 *
 * نام‌ها **escape** می‌شوند چون عنوانِ سناریو متنِ آدم است و نقطه و پرانتز
 * دارد؛ بی escape، `--grep` آن‌ها را الگو می‌خواند و یا زیادی می‌گیرد یا
 * هیچ. و لنگر (`^...$`) عمدی نیست: عنوانِ پیش‌نویس در گزارش `[پیش‌نویس]`
 * می‌گیرد، پس تطبیقِ کامل هرگز نمی‌خورد.
 */
export function benchGrep(names) {
  const clean = (Array.isArray(names) ? names : [names])
    .map((name) => String(name ?? '').trim())
    .filter(Boolean);

  if (!clean.length) return '';
  return clean.map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|');
}

/**
 * نام‌های بنچی که در این اجراها دیده شده‌اند، تازه‌ترین اول.
 *
 * برای کشویی فیلتر است: فهرستِ ثابتِ از پیش تعریف‌شده‌ای وجود ندارد و نباید
 * داشته باشد — بنچ چیزی است که کاربر همان لحظه اسمش را می‌گذارد.
 */
export function benchesOf(runs) {
  const seen = new Set();
  for (const run of runs || []) {
    const name = normalizeBench(run?.bench);
    if (name) seen.add(name);
  }
  return [...seen];
}
