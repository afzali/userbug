import { fixturesDir, listFixtures } from '../../../../../../src/knowledge/fixtures.js';
import { listAccounts } from '../../../../../../src/knowledge/credentials.js';

/**
 * «دادهٔ آزمون» — حساب‌ها و فایل‌هایی که سناریوها مصرف می‌کنند.
 *
 * ── چرا چک‌ها از اینجا رفتند ──
 *
 * کاربر پرسید: «چرا در صفحهٔ پیکربندی چکِ همگانی داریم و اصلاً بدرد
 * می‌خورد؟» بدرد می‌خورد — تنها سنجشِ خودکاری است که بی سناریو هم کار
 * می‌کند — ولی جایش غلط بود: لحظهٔ سراغ رفتنش وقتی است که یک چک قلابی
 * داده، یعنی وسطِ صفحهٔ یافته‌ها. به آنجا رفت.
 *
 * آنچه ماند، یک جنس است: **داده**. حسابی که سناریو با آن وارد می‌شود و
 * فایلی که آپلود می‌کند — هر دو ورودیِ اجرا هستند، نه تنظیم و نه شناخت.
 *
 * ── و چرا اصلاً از صفحهٔ شناخت بیرون آمدند ──
 *
 * آن صفحه یازده بخش داشت و این‌ها جنسِ دیگری بودند. هیچ‌کدام «آنچه از این
 * اپ می‌دانیم» نیستند؛ ورودیِ اجرا هستند. کنارِ هم بودنشان دو هزینه داشت:
 * صفحهٔ شناخت طولانی می‌شد، و این‌ها در انتهایش گم می‌شدند.
 *
 * مرزش ساده است: چیزی که با **گشت و سورس و مدل** پر می‌شود شناخت است؛
 * چیزی که **کاربر می‌دهد تا اجرا مصرفش کند**، داده.
 */
export async function load({ params }) {
  const target = params.target;
  const safely = (fn, fallback) => {
    try {
      return fn();
    } catch {
      return fallback;
    }
  };

  return {
    fixtures: await listFixtures(target).catch(() => []),
    // مسیر نشان داده می‌شود چون کاربر باید بداند فایل را کجا بگذارد
    fixturesPath: safely(() => fixturesDir(target), ''),
    accounts: safely(() => listAccounts(target), []),
  };
}
